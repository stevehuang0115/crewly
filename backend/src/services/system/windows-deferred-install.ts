/**
 * Windows upgrade: install after Crewly has exited.
 *
 * npm replaces a global package by renaming its directory aside. Windows
 * refuses the rename (EBUSY) while any process runs from the directory or
 * has it as its working directory, and the backend, its `crewly start`
 * parent and agent terminals all do. So on Windows the running backend does
 * not install. It hands the job to a small helper script that lives in the
 * Crewly home (outside the package):
 *
 * 1. the backend writes the plan, the helper script and the shutdown marker,
 *    starts the helper detached, and exits the usual restart way;
 * 2. `crewly start` and the supervisor see the marker and stay down;
 * 3. the helper waits for them to exit, ends what is left of the backend's
 *    process tree, runs npm (a few attempts), removes the marker and starts
 *    Crewly again, whether the install worked or not.
 *
 * The pending-upgrade marker written before the exit makes the next boot
 * report the outcome: upgraded, or still on the old version.
 *
 * @module services/system/windows-deferred-install
 */

import { spawn } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';
import { AUTO_UPDATE_CONSTANTS } from '../../constants.js';
import { clearShutdownMarker, shutdownMarkerPath, writeShutdownMarker } from './shutdown-marker.js';

/** Everything the helper needs, written next to it as JSON. */
export interface DeferredInstallPlan {
	/** Target version */
	version: string;
	/** npm executable */
	npmCommand: string;
	/** npm arguments */
	npmArgs: string[];
	/** Package directory npm replaces */
	packageRoot: string;
	/** Directory npm and the relaunch run in (outside the package) */
	cwd: string;
	/** Processes that must be gone before npm runs (backend, `crewly start` parent) */
	waitForPids: number[];
	/** Process whose leftover descendants are ended before npm runs (the backend) */
	treeRootPid: number;
	/** Shutdown marker: present while the helper owns the downtime; removed = cancelled */
	shutdownMarker: string;
	/** Log file the helper appends to */
	logFile: string;
	/** How Crewly is started again */
	relaunch: { command: string; args: string[] };
	/** How long to wait for the processes to exit (ms) */
	exitWaitMs: number;
	/** npm attempts */
	attempts: number;
	/** Wait between npm attempts (ms) */
	retryDelayMs: number;
}

/** What {@link startDeferredInstall} touches; injected in tests. */
export interface DeferredInstallDeps {
	crewlyHome: string;
	packageRoot: string;
	npmCommand: string;
	npmArgs: string[];
	version: string;
	logFile: string;
	nodePath?: string;
	backendPid?: number;
	parentPid?: number;
	/** Start the helper without waiting for it */
	launch?: (nodePath: string, scriptPath: string, planPath: string, cwd: string) => void;
}

/**
 * How Crewly comes back after the install: through the service launcher when
 * `crewly service install` set one up (it brings the supervisor back too),
 * otherwise by running `crewly start` directly.
 *
 * @param crewlyHome - Crewly home
 * @param packageRoot - Crewly package root
 * @param nodePath - Node executable
 * @returns Command and arguments
 */
export function resolveRelaunch(crewlyHome: string, packageRoot: string, nodePath: string): { command: string; args: string[] } {
	const launcher = path.join(crewlyHome, AUTO_UPDATE_CONSTANTS.WINDOWS_LAUNCHER_FILE);
	const supervisor = path.join(crewlyHome, AUTO_UPDATE_CONSTANTS.WINDOWS_SUPERVISOR_FILE);
	if (fs.existsSync(launcher) && fs.existsSync(supervisor)) return { command: 'wscript.exe', args: [launcher] };
	return { command: nodePath, args: [path.join(packageRoot, AUTO_UPDATE_CONSTANTS.CLI_ENTRY), 'start', '--no-browser'] };
}

/**
 * The helper script: self-contained CommonJS, no dependencies, run from the
 * Crewly home. It always removes the shutdown marker and relaunches Crewly
 * at the end, so a failed install leaves the old version running, not
 * nothing. It does nothing when the marker is gone before the processes
 * exit (the restart was called off).
 *
 * @returns Script source
 */
export function generateDeferredInstallHelper(): string {
	return `'use strict';
// Crewly deferred upgrade (generated by Crewly; do not edit).
// Waits for Crewly to exit, runs npm, starts Crewly again.
const { spawn, execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const plan = JSON.parse(fs.readFileSync(process.argv[2], 'utf-8'));
const WIN = process.platform === 'win32';

function log(line) {
  try {
    fs.mkdirSync(path.dirname(plan.logFile), { recursive: true });
    fs.appendFileSync(plan.logFile, new Date().toISOString() + ' [deferred] ' + line + '\\n');
  } catch (_) { /* best-effort */ }
}
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
function alive(pid) {
  try { process.kill(pid, 0); return true; } catch (error) { return error.code === 'EPERM'; }
}
function quote(word) {
  return /[\\s&|<>^()"]/.test(word) ? '"' + word.replace(/"/g, '""') + '"' : word;
}

// Descendants of the backend (agent terminals and what runs in them), taken
// while the tree still exists. This helper and its own children are left out.
function descendantsOf(root) {
  if (!WIN) return [];
  try {
    const out = execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command',
      'Get-CimInstance Win32_Process | ForEach-Object { "$($_.ProcessId) $($_.ParentProcessId)" }'],
      { encoding: 'utf-8', timeout: 30000, windowsHide: true });
    const children = new Map();
    for (const line of out.split(/\\r?\\n/)) {
      const parts = line.trim().split(/\\s+/).map(Number);
      if (parts.length !== 2 || !parts[0]) continue;
      if (!children.has(parts[1])) children.set(parts[1], []);
      children.get(parts[1]).push(parts[0]);
    }
    const found = [];
    const queue = [root];
    while (queue.length) {
      for (const pid of children.get(queue.shift()) || []) {
        if (pid === process.pid || found.includes(pid)) continue;
        found.push(pid);
        queue.push(pid);
      }
    }
    return found;
  } catch (error) {
    log('could not list the process tree: ' + error.message);
    return [];
  }
}

function endLeftovers(pids) {
  const left = pids.filter(alive);
  if (!left.length) return;
  log('ending ' + left.length + ' leftover process(es) of the old backend');
  for (const pid of left) {
    try { execFileSync('taskkill.exe', ['/F', '/PID', String(pid)], { stdio: 'ignore', timeout: 15000, windowsHide: true }); } catch (_) { /* gone */ }
  }
}

function runNpm() {
  return new Promise((resolve) => {
    let tail = '';
    let child;
    try {
      child = spawn(WIN ? quote(plan.npmCommand) : plan.npmCommand, WIN ? plan.npmArgs.map(quote) : plan.npmArgs, {
        cwd: plan.cwd, shell: WIN, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'],
      });
    } catch (error) { resolve({ code: null, tail: error.message }); return; }
    const onData = (chunk) => { tail = (tail + chunk.toString()).slice(-2000); };
    child.stdout.on('data', onData);
    child.stderr.on('data', onData);
    child.once('error', (error) => resolve({ code: null, tail: error.message }));
    child.once('close', (code) => resolve({ code, tail }));
  });
}

function installedVersion() {
  try { return JSON.parse(fs.readFileSync(path.join(plan.packageRoot, 'package.json'), 'utf-8')).version || null; } catch (_) { return null; }
}

function relaunch() {
  try { fs.rmSync(plan.shutdownMarker, { force: true }); } catch (_) { /* absent */ }
  try {
    spawn(plan.relaunch.command, plan.relaunch.args, { cwd: plan.cwd, detached: true, stdio: 'ignore', windowsHide: true }).unref();
    log('Crewly is starting again (' + (installedVersion() || 'unknown version') + ' on disk)');
  } catch (error) {
    log('could not start Crewly again: ' + error.message + '. Start it by hand with \`crewly start\`.');
  }
}

async function main() {
  log('waiting for Crewly to exit before installing ' + plan.version);
  const leftovers = descendantsOf(plan.treeRootPid);
  const deadline = Date.now() + plan.exitWaitMs;
  while (plan.waitForPids.some(alive)) {
    if (!fs.existsSync(plan.shutdownMarker)) { log('the restart was called off; nothing installed'); return; }
    if (Date.now() > deadline) {
      log('Crewly did not exit in time; nothing installed');
      try { fs.rmSync(plan.shutdownMarker, { force: true }); } catch (_) { /* absent */ }
      return;
    }
    await sleep(1000);
  }
  try {
    endLeftovers(leftovers);
    await sleep(WIN ? 2000 : 0);
    for (let attempt = 1; attempt <= plan.attempts; attempt++) {
      const result = await runNpm();
      const onDisk = installedVersion();
      if (result.code === 0 && onDisk === plan.version) { log('installed ' + plan.version + ' (attempt ' + attempt + ')'); return; }
      const lines = String(result.tail).split(/\\r?\\n/).filter((l) => l.trim()).slice(-6).join(' | ');
      log('attempt ' + attempt + ' of ' + plan.attempts + ' failed (npm exit ' + result.code + ', ' + (onDisk || 'no package') + ' on disk): ' + lines);
      if (attempt < plan.attempts) await sleep(plan.retryDelayMs);
    }
    log('could not install ' + plan.version + '; starting what is on disk');
  } finally {
    relaunch();
  }
}

process.on('uncaughtException', (error) => { log('error: ' + (error && error.stack ? error.stack : error)); relaunch(); process.exit(1); });
main().catch((error) => { log('failed: ' + (error && error.stack ? error.stack : error)); });
`;
}

/**
 * Hand the install to the helper: write the plan, the script and the
 * shutdown marker, and start the helper detached. The caller then exits the
 * backend; the helper does nothing until it has.
 *
 * @param deps - Paths, npm command and injectable launch
 * @returns The plan that was written
 * @throws When a file cannot be written or the helper cannot be started
 *
 * @example
 * ```ts
 * startDeferredInstall({ crewlyHome, packageRoot, npmCommand, npmArgs, version: '1.47.0', logFile });
 * ```
 */
export function startDeferredInstall(deps: DeferredInstallDeps): DeferredInstallPlan {
	const nodePath = deps.nodePath ?? process.execPath;
	const backendPid = deps.backendPid ?? process.pid;
	const parentPid = deps.parentPid ?? process.ppid;
	const runDir = path.join(deps.crewlyHome, 'run');
	const scriptPath = path.join(deps.crewlyHome, AUTO_UPDATE_CONSTANTS.DEFERRED_HELPER_FILE);
	const planPath = path.join(runDir, AUTO_UPDATE_CONSTANTS.DEFERRED_PLAN_FILE);
	const plan: DeferredInstallPlan = {
		version: deps.version,
		npmCommand: deps.npmCommand,
		npmArgs: deps.npmArgs,
		packageRoot: deps.packageRoot,
		cwd: deps.crewlyHome,
		waitForPids: [backendPid, parentPid].filter((pid) => Number.isInteger(pid) && pid > 1),
		treeRootPid: backendPid,
		shutdownMarker: shutdownMarkerPath(deps.crewlyHome),
		logFile: deps.logFile,
		relaunch: resolveRelaunch(deps.crewlyHome, deps.packageRoot, nodePath),
		exitWaitMs: AUTO_UPDATE_CONSTANTS.DEFERRED_EXIT_WAIT_MS,
		attempts: AUTO_UPDATE_CONSTANTS.DEFERRED_ATTEMPTS,
		retryDelayMs: AUTO_UPDATE_CONSTANTS.DEFERRED_RETRY_DELAY_MS,
	};
	fs.mkdirSync(runDir, { recursive: true });
	fs.writeFileSync(scriptPath, generateDeferredInstallHelper(), 'utf-8');
	fs.writeFileSync(planPath, `${JSON.stringify(plan, null, 2)}\n`, 'utf-8');
	writeShutdownMarker(deps.crewlyHome, backendPid);
	try {
		(deps.launch ?? launchDetached)(nodePath, scriptPath, planPath, deps.crewlyHome);
	} catch (error) {
		clearShutdownMarker(deps.crewlyHome);
		throw error;
	}
	return plan;
}

/**
 * Call the handed-over install off (the restart did not happen): without the
 * marker the helper exits without installing.
 *
 * @param crewlyHome - Crewly home
 */
export function cancelDeferredInstall(crewlyHome: string): void {
	clearShutdownMarker(crewlyHome);
}

/**
 * Start the helper so it outlives this process.
 *
 * @param nodePath - Node executable
 * @param scriptPath - Helper script
 * @param planPath - Plan file
 * @param cwd - Working directory (outside the package)
 */
function launchDetached(nodePath: string, scriptPath: string, planPath: string, cwd: string): void {
	spawn(nodePath, [scriptPath, planPath], { cwd, detached: true, stdio: 'ignore', windowsHide: true }).unref();
}
